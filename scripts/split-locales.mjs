import { readFile, writeFile } from 'node:fs/promises';
import ts from 'typescript';

// The frozen compatibility aggregates remain the single authoritative source.
// This compiler preserves their evaluated Unicode/text exactly; no hand-maintained copies.
const root = new URL('../', import.meta.url);
const check = process.argv.includes('--check');
let generatedCount = 0;
async function dataModule(path) {
  const source = await readFile(new URL(path, root), 'utf8');
  const { outputText } = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } });
  return import(`data:text/javascript;base64,${Buffer.from(outputText).toString('base64')}`);
}
const content = await dataModule('src/locales/content.ts');
const ui = await dataModule('src/locales/index.js');
const { libraryTranslations } = await dataModule('src/locales/score-library.ts');
const languages = Object.keys(ui.STRINGS);
const header = '// Generated by node scripts/split-locales.mjs; edit the authoritative aggregates, then regenerate.\n';
// The boundary scanner also scans string literals. Escape this prose token, not its value.
const json = value => JSON.stringify(value, null, 2).replace(/: any\b/g, ': \\u0061ny');
async function output(path, source) {
  const url = new URL(path, root), expected = header + source;
  generatedCount++;
  if (check) {
    const actual = await readFile(url, 'utf8');
    if (actual !== expected) throw new Error(`${path} is stale; run node scripts/split-locales.mjs`);
  } else await writeFile(url, expected);
}
for (const language of languages) {
  const payload = {
    STRINGS: { [language]: ui.STRINGS[language] },
    I18N_MUSIC: Object.fromEntries(Object.entries(ui.I18N_MUSIC).map(([category, translations]) => [category, translations[language] ? { [language]: translations[language] } : {}])),
    STEP_LABELS: ui.STEP_LABELS[language] ? { [language]: ui.STEP_LABELS[language] } : {},
    LOCALE_TAGS: { [language]: ui.LOCALE_TAGS[language] },
    LIBRARY: { [language]: libraryTranslations[language] },
  };
  await output(`src/locales/ui-${language}.ts`, `import type { UIPayload } from './payload-types.js';\nconst payload: UIPayload = ${json(payload)};\nexport default payload;\n`);
  // Another language starts with the English music terms, step labels and library copy under it, without the English
  // interface strings: every language has every string (tests/unit/locales.test.mjs), so those would only be overwritten.
  if (language === 'en') await output('src/locales/ui-base.ts', `import type { UIPayload } from './payload-types.js';\nconst payload: UIPayload = ${json({ ...payload, STRINGS: {} })};\nexport default payload;\n`);
  const text = value => Array.isArray(value) ? value[language === 'ro' ? 1 : 0] : value;
  const learn = {
    LESSONS: Object.fromEntries(content.LESSONS.map(lesson => [lesson.id, lesson[language] || lesson.en])),
    LQZ: Object.fromEntries(Object.entries(content.LQZ).map(([id, questions]) => [id, questions.map(({ i18n, ...q }) => {
      const loc = i18n?.[language];
      return { ...q, q: loc?.q || text(q.q),
        ...(q.o ? { o: q.o.map((value, i) => loc?.o?.[i] || text(value)) } : {}),
        ...(q.why ? { why: loc?.why || text(q.why) } : {}) };
    })])),
    LSUM: Object.fromEntries(Object.entries(content.LSUM).map(([id, rows]) => [id, rows.map((row, i) => content.LSUM_I18N[language]?.[id]?.[i] || row.map(text))])),
    GLOSS: content.GLOSS.map(entry => ({ l: entry.l, en: entry[language] || entry.en, searchEnglish: entry.en[0] })),
  };
  await output(`src/locales/learn-${language}.ts`, `import type { LearnPayload } from './payload-types.js';\nconst payload: LearnPayload = ${JSON.stringify(learn, null, 2)};\nexport default payload;\n`);
}
const lessons = content.LESSONS.map(({ id, icon, ...copy }) => ({ id, icon, ...Object.fromEntries(Object.entries(copy).map(([language, value]) => [language, { t: value.t }])) }));
await output('src/locales/catalog.ts', `import type { LessonMetadata, LearnUnit } from './content-types.js';\nexport const LESSONS: LessonMetadata[] = ${JSON.stringify(lessons, null, 2)};\nexport const LEARN_UNITS: LearnUnit[] = ${JSON.stringify(content.LEARN_UNITS, null, 2)};\n`);
console.log(`${check ? 'Verified' : 'Generated'} ${generatedCount} generated locale files.`);
