import { parse } from 'acorn';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

function bindingNames(pattern, names = []) {
  if (!pattern) return names;
  if (pattern.type === 'Identifier') names.push(pattern.name);
  else if (pattern.type === 'ObjectPattern') for (const property of pattern.properties) {
    if (property.type === 'Property') bindingNames(property.value, names);
    else if (property.type === 'RestElement') bindingNames(property.argument, names);
  }
  else if (pattern.type === 'ArrayPattern') for (const element of pattern.elements) bindingNames(element, names);
  else if (pattern.type === 'RestElement' || pattern.type === 'AssignmentPattern') bindingNames(pattern.argument || pattern.left, names);
  return names;
}

export function topLevelBindings(source) {
  const ast = parse(source, {
    ecmaVersion: 'latest',
    sourceType: 'module',
    allowHashBang: true,
  });
  const writable = new Set();
  const readonly = new Set();
  for (const statement of ast.body) {
    if (statement.type === 'FunctionDeclaration' && statement.id) writable.add(statement.id.name);
    if (statement.type !== 'VariableDeclaration') continue;
    for (const declaration of statement.declarations) {
      for (const name of bindingNames(declaration.id)) {
        (statement.kind === 'const' ? readonly : writable).add(name);
      }
    }
  }
  return {
    writable: [...writable].sort(),
    readonly: [...readonly].filter(name => !writable.has(name)).sort(),
  };
}

export function bridgeSource(source) {
  const { writable, readonly } = topLevelBindings(source);
  const lines = [
    '/* Generated by scripts/generate-bridge.mjs. Injected into app.js during development and build. */',
  ];
  for (const name of writable)
    lines.push(`Object.defineProperty(window, ${JSON.stringify(name)}, { configurable: true, get: () => ${name}, set: value => { ${name} = value; } });`);
  for (const name of readonly)
    lines.push(`Object.defineProperty(window, ${JSON.stringify(name)}, { configurable: true, get: () => ${name} });`);
  return lines.join('\n') + '\n';
}

export async function generateBridge(input, output) {
  const source = await readFile(input, 'utf8');
  await writeFile(output, bridgeSource(source));
  return topLevelBindings(source);
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) {
  const input = resolve(process.argv[2] || 'src/legacy/app.js');
  const output = resolve(process.argv[3] || 'src/legacy/bridge.js');
  const names = await generateBridge(input, output);
  console.log(`Generated ${output} (${names.writable.length + names.readonly.length} bindings)`);
}
