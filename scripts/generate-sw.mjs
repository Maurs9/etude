import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { join, relative, resolve } from 'node:path';

const SW_FILE = 'sw.js';

export async function publishedManifest(directory, include = null) {
  const root = resolve(directory);
  const wanted = include ? new Set(include.map(file => file.replaceAll('\\', '/'))) : null;
  const files = [];
  async function visit(dir) {
    for (const entry of await readdir(dir, { withFileTypes: true })) {
      const path = join(dir, entry.name);
      if (entry.isDirectory()) await visit(path);
      else if (entry.isFile()) {
        const url = relative(root, path).replaceAll('\\', '/');
        if (url !== SW_FILE && (!wanted || wanted.has(url))) files.push({ url, path });
      }
    }
  }
  await visit(root);
  files.sort((a, b) => a.url.localeCompare(b.url));
  return Promise.all(files.map(async ({ url, path }) => ({
    url,
    hash: createHash('sha256').update(await readFile(path)).digest('hex'),
  })));
}

export function workerSource(manifest) {
  return `/* Generated by scripts/generate-sw.mjs. Do not edit by hand. */
'use strict';
const CACHE_PREFIX = 'etude-';
const META_CACHE = 'etude-active';
const NETWORK_TIMEOUT_MS = 8000;
const PRECACHE = ${JSON.stringify(manifest)};
const SCOPE = new URL(self.registration.scope);
const CACHE_NAME = CACHE_PREFIX + PRECACHE.map(entry => entry.hash).join('').slice(0, 24);
const META_URL = new URL('__etude_active__', SCOPE).href;
const SHELL_URL = new URL('etude.html', SCOPE).href;
const PRECACHE_URLS = new Map(PRECACHE.map(entry => [new URL(entry.url, SCOPE).href, entry.hash]));

self.addEventListener('install', event => {
  event.waitUntil((async () => {
    try {
      const cache = await caches.open(CACHE_NAME);
      for (const entry of PRECACHE) {
        const url = new URL(entry.url, SCOPE).href;
        const old = await findCached(url, entry.hash);
        if (old) {
          await cache.put(url, old.clone());
          continue;
        }
        const response = await fetch(new Request(url, { cache: 'no-cache' }));
        await putChecked(cache, url, response, entry.hash);
      }
      await self.skipWaiting();
    } catch (error) {
      await caches.delete(CACHE_NAME);
      throw error;
    }
  })());
});

self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    const meta = await readMeta();
    const keys = await caches.keys();
    const legacy = keys.filter(key => key.startsWith(CACHE_PREFIX) && key !== CACHE_NAME && key !== META_CACHE);
    const previous = meta?.active && meta.active !== CACHE_NAME ? meta.active : legacy.at(-1) || null;
    await writeMeta({ active: CACHE_NAME, previous });
    const keep = new Set([CACHE_NAME, previous, META_CACHE].filter(Boolean));
    await Promise.all(keys
      .filter(key => key.startsWith(CACHE_PREFIX) && !keep.has(key))
      .map(key => caches.delete(key)));
    if (self.registration.navigationPreload) {
      try { await self.registration.navigationPreload.disable(); } catch (_) {}
    }
    await self.clients.claim();
  })());
});

self.addEventListener('fetch', event => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== SCOPE.origin) return;
  if (request.mode === 'navigate') {
    event.respondWith(navigation(event));
    return;
  }
  const bare = url.origin + url.pathname;
  // Route static requests through every retained version. A tab from the
  // previous release can still request a hashed asset that is absent from the
  // current manifest, and the previous cache is intentionally kept for it.
  if (PRECACHE_URLS.has(bare) || request.destination !== '') {
    event.respondWith(asset(request, bare, PRECACHE_URLS.get(bare)));
  }
});

function timeout(ms) {
  return new Promise((_, reject) => setTimeout(() => reject(new Error('timeout')), ms));
}

async function navigation(event) {
  const network = fetch(event.request);
  event.waitUntil(network.then(() => {}, () => {}));
  try {
    const response = await Promise.race([network, timeout(NETWORK_TIMEOUT_MS)]);
    if (response.ok) return response;
  } catch (_) {}
  return (await findActiveCached(SHELL_URL)) || Response.error();
}

async function asset(request, url, expectedHash) {
  const hit = await findCached(url, expectedHash);
  if (hit) return hit;
  return fetch(request);
}

async function findCached(url, expectedHash) {
  const keys = await caches.keys();
  const names = keys.filter(key => key.startsWith(CACHE_PREFIX));
  for (const name of names) {
    const cache = await caches.open(name);
    const hit = await cache.match(url);
    if (!hit) continue;
    if (!expectedHash || await digest(hit.clone()) === expectedHash) return hit;
  }
  return null;
}

async function findActiveCached(url) {
  const meta = await readMeta();
  if (meta?.active) {
    const hit = await (await caches.open(meta.active)).match(url);
    if (hit) return hit;
  }
  return findCached(url);
}

async function putChecked(cache, url, response, expectedHash) {
  if (!response.ok || response.type === 'opaque') throw new Error('Precache request failed: ' + url);
  if (await digest(response.clone()) !== expectedHash) throw new Error('Precache hash mismatch: ' + url);
  await cache.put(url, response.clone());
}

async function digest(response) {
  const bytes = await response.arrayBuffer();
  const hash = await crypto.subtle.digest('SHA-256', bytes);
  return [...new Uint8Array(hash)].map(byte => byte.toString(16).padStart(2, '0')).join('');
}

async function readMeta() {
  const cache = await caches.open(META_CACHE);
  const response = await cache.match(META_URL);
  if (!response) return null;
  try { return await response.json(); } catch (_) { return null; }
}

async function writeMeta(value) {
  const cache = await caches.open(META_CACHE);
  await cache.put(META_URL, new Response(JSON.stringify(value), {
    headers: { 'content-type': 'application/json' },
  }));
}
`;
}

export async function generateWorker(directory, output, include = null) {
  const manifest = await publishedManifest(directory, include);
  await writeFile(output, workerSource(manifest));
  return manifest;
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(new URL(import.meta.url).pathname)) {
  const directory = resolve(process.argv[2] || 'dist/etude');
  const output = resolve(process.argv[3] || join(directory, SW_FILE));
  const manifest = await generateWorker(directory, output);
  console.log(`Generated ${output} (${manifest.length} precached files)`);
}
