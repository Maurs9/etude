export const libraryTranslations: Readonly<Record<string, Copy>> = { en, ro, es, fr, de, it, 'pt-BR': ptBR };
const tokens = (value: string): string => [...value.matchAll(/\{(\w+)\}/g)].map(match => match[1]).sort().join(',');
/** Validate translated placeholders at module load, so a broken translation cannot silently lose a count. */
for (const [language, copy] of Object.entries(libraryTranslations)) {
  for (const key of Object.keys(en) as LibraryTextKey[]) {
    if (tokens(copy[key]) !== tokens(en[key])) throw new Error(`Library translation placeholders: ${language}.${key}`);
  }
}
export function libraryText(language: string, key: LibraryTextKey, values: Record<string, string | number> = {}): string {
  const copy = libraryTranslations[language] ?? en;
  return copy[key].replace(/\{(\w+)\}/g, (placeholder, name: string) => values[name] === undefined ? placeholder : String(values[name]));
}
